"""Validate captured evaluations and replay policies through the decision engine."""

import math
from pathlib import Path
import sys

SCRIPTS_DIR = Path(__file__).resolve().parent.parent / "skills" / "autarch" / "scripts"
sys.path.insert(0, str(SCRIPTS_DIR))

import decide

THRESHOLD_FIELDS = frozenset({
    "auto_select", "review", "min_gap", "human_preference", "sufficiency", "blocker_confidence",
})
PARSED_FIELDS = frozenset({
    "human_preference", "choice", "confidence", "probabilities", "scores",
    "evidence_sufficiency", "blocker_class", "blocker_confidence",
})
SNAPSHOT_FIELDS = frozenset({
    "schema_version", "parsed", "thresholds", "gate_order", "evaluated_option_ids",
})


def _require_fields(value, fields, label):
    if not isinstance(value, dict) or set(value) != fields:
        raise ValueError(f"{label} must contain exactly the required fields")


def _number(value, maximum, label):
    try:
        return decide._require_number(value, 0.0, maximum, label)
    except (decide.ProviderError, OverflowError) as error:
        raise ValueError(f"invalid {label}: {error}") from None


def _validate_thresholds(thresholds):
    _require_fields(thresholds, THRESHOLD_FIELDS, "thresholds")
    for name, value in thresholds.items():
        _number(value, 1.0, f"thresholds.{name}")


def _validate_order(gate_order):
    if gate_order not in decide.GATE_ORDERS:
        raise ValueError("gate_order must be human_first or evidence_first")


def _require_finite(value):
    # State weights also contribute to resolve; NaN/Infinity must not reach it.
    if isinstance(value, dict):
        for item in value.values():
            _require_finite(item)
    elif isinstance(value, list):
        for item in value:
            _require_finite(item)
    elif isinstance(value, (float, int)):
        try:
            finite = math.isfinite(value)
        except OverflowError:
            finite = False
        if not finite:
            raise ValueError("state must not contain non-finite numbers")


def _valid_id(value):
    return (isinstance(value, str) and decide.ID_PATTERN.fullmatch(value) is not None
            and "__" not in value)


def _validate_parsed(parsed, state):
    _require_fields(parsed, PARSED_FIELDS, "parsed")
    option_ids = {a["id"] for a in state["alternatives"]}
    for name in ("human_preference", "confidence", "evidence_sufficiency", "blocker_confidence"):
        _number(parsed[name], 1.0, f"parsed.{name}")
    choice = parsed["choice"]
    if not _valid_id(choice) or choice not in option_ids:
        raise ValueError("parsed.choice must be an evaluated option id")
    probabilities = parsed["probabilities"]
    _require_fields(probabilities, option_ids, "parsed.probabilities")
    for option_id, probability in probabilities.items():
        _number(probability, 1.0, f"parsed.probabilities[{option_id}]")
    if probabilities[choice] != max(probabilities.values()):
        raise ValueError("parsed.choice must match the highest probability")
    if parsed["blocker_class"] not in decide.BLOCKER_CLASSES:
        raise ValueError("parsed.blocker_class must be a known blocker class")
    criteria = state.get("criteria") or []
    _require_fields(parsed["scores"], {c["id"] for c in criteria}, "parsed.scores")
    for criterion in criteria:
        criterion_id = criterion["id"]
        if not _valid_id(criterion_id):
            raise ValueError("criterion id must match the required pattern")
        scores = parsed["scores"][criterion_id]
        _require_fields(scores, option_ids, f"parsed.scores[{criterion_id}]")
        for option_id, score in scores.items():
            _number(score, len(criterion["rubric"]) - 1,
                    f"parsed.scores[{criterion_id}][{option_id}]")


def replay_resolution(state: dict, snapshot: dict, thresholds: dict, gate_order: str) -> dict:
    """Replay validated unrounded signals against the original state and a policy.

    Capture settings are validated for provenance; the supplied thresholds and
    gate order select the replay policy. Constraints are regenerated by the engine.
    Neither the state nor the snapshot is mutated.
    """
    _require_fields(snapshot, SNAPSHOT_FIELDS, "snapshot")
    if type(snapshot["schema_version"]) is not int or snapshot["schema_version"] != 1:
        raise ValueError("unsupported evaluation snapshot schema_version")
    _validate_thresholds(snapshot["thresholds"])
    _validate_thresholds(thresholds)
    _validate_order(snapshot["gate_order"])
    _validate_order(gate_order)
    _require_finite(state)
    evaluated, constraint_check, early = decide.check_constraints(state)
    if early is not None:
        raise ValueError(f"state cannot be evaluated: {early['rule']}")
    option_ids = snapshot["evaluated_option_ids"]
    if (not isinstance(option_ids, list) or not all(_valid_id(item) for item in option_ids)
            or len(set(option_ids)) != len(option_ids)
            or option_ids != [a["id"] for a in evaluated["alternatives"]]):
        raise ValueError("evaluated_option_ids must match the engine's evaluated options exactly")
    parsed, _ = decide.redact(snapshot["parsed"])
    _validate_parsed(parsed, evaluated)
    resolution = decide.resolve(evaluated, parsed, thresholds,
                                gate_order=gate_order)
    resolution["constraint_check"] = decide.redact(constraint_check)[0]
    return resolution
